import { aliasNorm, eCode, type Rules } from '../../packages/rules-engine/src/index.ts';
import { lit } from '../lib.ts';
import type { TaxonomyEntry } from './parse.ts';

export interface ImportOptions {
  langs: string[];
  /** Skip entries whose names or codes already map to a rule in this bundle. */
  known?: Rules;
}

export function offIngredientId(tag: string): string {
  return `off_${tag.replace(/[^a-z0-9]+/gi, '_').toLowerCase()}`.replace(/_+$/, '').slice(0, 80);
}

export interface ImportPlan {
  entries: Array<{ id: string; tag: string; displayName: string; aliases: Array<{ alias: string; lang: string; kind: 'name' | 'e_number' }> }>;
  skippedKnown: number;
}

export function planImport(entries: TaxonomyEntry[], opts: ImportOptions): ImportPlan {
  const plan: ImportPlan = { entries: [], skippedKnown: 0 };
  for (const e of entries) {
    const aliases: ImportPlan['entries'][number]['aliases'] = [];
    for (const lang of opts.langs) for (const n of e.names[lang] ?? []) aliases.push({ alias: n, lang, kind: 'name' });
    const code = e.props['e_number'];
    if (code && eCode(`e${code}`)) aliases.push({ alias: `E${code}`, lang: 'en', kind: 'e_number' });
    // names that are themselves E-codes ("E129") are stored as e_number aliases
    for (const a of aliases) if (a.kind === 'name' && eCode(a.alias)) a.kind = 'e_number';
    const usable = aliases.filter((a) => {
      try {
        return aliasNorm(a) !== '';
      } catch {
        return false;
      }
    });
    if (!usable.length) continue;
    if (opts.known) {
      const k = opts.known;
      const hit = usable.some((a) => (a.kind === 'e_number' ? k.eNumbers.has(aliasNorm(a)) : k.aliases.has(aliasNorm(a))));
      if (hit) {
        plan.skippedKnown++;
        continue;
      }
    }
    const displayName = e.names['en']?.[0] ?? usable[0]!.alias;
    plan.entries.push({ id: offIngredientId(e.tag), tag: e.tag, displayName, aliases: usable });
  }
  return plan;
}

/** Inactive, untiered ingredients plus aliases. Nothing becomes active until the admin gives it a tier. */
export function planToSql(plan: ImportPlan, source: string): string {
  const out = [
    `-- GENERATED by scripts/import-off-taxonomy from ${source}`,
    '-- Data from Open Food Facts, available under the Open Database License (ODbL).',
    '-- Rows are inactive and untiered; activate them in the admin after giving them a tier.',
    'begin;',
    `insert into public.categories (id, label, toggleable, sort_order) values ('unreviewed', 'Unreviewed', false, 999) on conflict (id) do nothing;`,
  ];
  for (const e of plan.entries) {
    out.push(
      `insert into public.ingredients (id, display_name, category, off_tag, is_active) values (${lit(e.id)}, ${lit(e.displayName)}, 'unreviewed', ${lit(e.tag)}, false) on conflict do nothing;`,
    );
    for (const a of e.aliases) {
      out.push(
        `insert into public.aliases (alias, alias_norm, ingredient_id, lang, kind) values (${lit(a.alias)}, '', ${lit(e.id)}, ${lit(a.lang)}, '${a.kind}') on conflict (alias_norm) do nothing;`,
      );
    }
  }
  out.push('commit;', '');
  return out.join('\n');
}
