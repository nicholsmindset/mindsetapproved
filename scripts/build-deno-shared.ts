/**
 * Bundles packages/rules-engine into one ESM file for Supabase Edge Functions (Deno can't resolve the
 * engine's extensionless imports), and copies the regression fixtures next to it.
 *   pnpm deno:shared
 * A test fails if the committed files are stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { build } from 'esbuild';
import { ROOT } from './lib.ts';

export const SHARED = resolve(ROOT, 'supabase/functions/_shared');
const BANNER = '// GENERATED by scripts/build-deno-shared.ts from packages/rules-engine. Do not edit.\n// deno-lint-ignore-file';

export async function buildDenoShared(): Promise<{ engine: string; fixtures: string }> {
  const out = await build({
    entryPoints: [resolve(ROOT, 'packages/rules-engine/src/index.ts')],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    write: false,
    banner: { js: BANNER },
    logLevel: 'silent',
  });
  const engine = out.outputFiles[0]!.text;
  const fixtures = readFileSync(resolve(ROOT, 'packages/rules-engine/test/fixtures/labels.json'), 'utf8');
  return { engine, fixtures };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { engine, fixtures } = await buildDenoShared();
  writeFileSync(resolve(SHARED, 'rules-engine.js'), engine);
  writeFileSync(resolve(SHARED, 'fixtures.json'), fixtures);
  console.log(`Wrote ${SHARED}/rules-engine.js (${(engine.length / 1024).toFixed(1)} KB) and fixtures.json`);
}
