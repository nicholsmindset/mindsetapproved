/**
 * Accuracy benchmark on real products (data/benchmark/products.json, see fetch.ts).
 *   pnpm benchmark            -> prints a summary and writes data/benchmark/report.md
 * Coverage = share of ingredient items (leaves) that matched a rule. It measures how much of real labels the
 * database understands; correctness of each match is audited from the "what triggered each rule" table.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { analyze, compileBundle, loadRules, rowsFromSource, type Rules, type Verdict } from '../../packages/rules-engine/src/index.ts';
import { readStarter, ROOT } from '../lib.ts';
import type { BenchProduct } from './fetch.ts';

export interface BenchResult {
  excludedNonFood: number;
  products: number;
  leaves: number;
  matchedLeaves: number;
  coverage: number;
  fullyCovered: number;
  byCountry: Record<string, { products: number; coverage: number; verdicts: Record<Verdict, number> }>;
  verdicts: Record<Verdict, number>;
  topUnmatched: Array<{ term: string; products: number }>;
  triggers: Record<string, Array<{ text: string; count: number }>>;
}

export function loadProducts(): BenchProduct[] {
  return (JSON.parse(readFileSync(resolve(ROOT, 'data/benchmark/products.json'), 'utf8')) as { products: BenchProduct[] }).products;
}

export function starterRules(): Rules {
  return loadRules(compileBundle({ ...rowsFromSource(readStarter()), generatedAt: 'benchmark' }));
}

const emptyVerdicts = (): Record<Verdict, number> => ({ approved: 0, caution: 0, not_approved: 0, cant_verify: 0 });

/** OFF lists some cosmetics and mineral-water analyses under food; they are reported separately, not scored. */
const NON_FOOD = /\b(sodium laur(?:yl|eth) sulfate|dimethicone|cocamidopropyl|parfum|methylparaben|cetearyl alcohol|polyquaternium|aqua\s*\/\s*water|mg\/l|mg l\b.*mg l\b)/i;
export function isNonFood(p: BenchProduct): boolean {
  return NON_FOOD.test(p.ingredients);
}

export function runBenchmark(all: BenchProduct[], rules: Rules): BenchResult {
  const products = all.filter((p) => !isNonFood(p));
  let leaves = 0;
  let matched = 0;
  let full = 0;
  const verdicts = emptyVerdicts();
  const countries: Record<string, { products: number; leaves: number; matched: number; verdicts: Record<Verdict, number> }> = {};
  const unmatched = new Map<string, Set<string>>();
  const triggers = new Map<string, Map<string, number>>();

  for (const p of products) {
    const r = analyze(p.ingredients, rules);
    const items = r.items.filter((i) => !i.container);
    const m = items.filter((i) => i.matches.length > 0).length;
    leaves += items.length;
    matched += m;
    if (m === items.length) full++;
    verdicts[r.verdict]++;
    const c = (countries[p.country] ??= { products: 0, leaves: 0, matched: 0, verdicts: emptyVerdicts() });
    c.products++;
    c.leaves += items.length;
    c.matched += m;
    c.verdicts[r.verdict]++;
    for (const t of r.unmatched) (unmatched.get(t) ?? unmatched.set(t, new Set()).get(t)!).add(p.code);
    for (const it of r.items) {
      for (const mm of it.matches) {
        const map = triggers.get(mm.ingredientId) ?? triggers.set(mm.ingredientId, new Map()).get(mm.ingredientId)!;
        const key = `${it.key}${mm.possible ? ' (possible)' : ''}`;
        map.set(key, (map.get(key) ?? 0) + 1);
      }
    }
  }

  return {
    excludedNonFood: all.length - products.length,
    products: products.length,
    leaves,
    matchedLeaves: matched,
    coverage: leaves ? matched / leaves : 0,
    fullyCovered: full,
    verdicts,
    byCountry: Object.fromEntries(
      Object.entries(countries).map(([k, v]) => [k, { products: v.products, coverage: v.leaves ? v.matched / v.leaves : 0, verdicts: v.verdicts }]),
    ),
    topUnmatched: [...unmatched.entries()]
      .map(([term, s]) => ({ term, products: s.size }))
      .sort((a, b) => b.products - a.products || a.term.localeCompare(b.term))
      .slice(0, 600),
    triggers: Object.fromEntries(
      [...triggers.entries()].map(([id, m]) => [
        id,
        [...m.entries()].map(([text, count]) => ({ text, count })).sort((a, b) => b.count - a.count).slice(0, 12),
      ]),
    ),
  };
}

const pct = (n: number) => `${(n * 100).toFixed(1)}%`;

export function reportMarkdown(r: BenchResult, rules: Rules): string {
  const lines = [
    '# Accuracy benchmark',
    '',
    'Generated by `pnpm benchmark` from `data/benchmark/products.json` (the most-scanned products with English ingredient text in each country, from Open Food Facts under the ODbL).',
    '',
    `${r.excludedNonFood} listed products were not food (cosmetics or mineral-water analyses) and are excluded.`,
    '',
    `**Coverage: ${pct(r.coverage)}** of ${r.leaves.toLocaleString('en')} ingredient items across ${r.products} products matched a rule. ${r.fullyCovered} products (${pct(r.fullyCovered / r.products)}) were fully understood.`,
    '',
    'Coverage means the database recognised the ingredient. Whether each match is *correct* is audited in "What triggered each rule" below.',
    '',
    '| Country | Products | Coverage | Approved | Caution | Not Approved | Can’t verify |',
    '|---|---:|---:|---:|---:|---:|---:|',
    ...Object.entries(r.byCountry).map(
      ([k, v]) => `| ${k.toUpperCase()} | ${v.products} | ${pct(v.coverage)} | ${v.verdicts.approved} | ${v.verdicts.caution} | ${v.verdicts.not_approved} | ${v.verdicts.cant_verify} |`,
    ),
    `| **All** | ${r.products} | ${pct(r.coverage)} | ${r.verdicts.approved} | ${r.verdicts.caution} | ${r.verdicts.not_approved} | ${r.verdicts.cant_verify} |`,
    '',
    '## Most common unrecognised terms',
    '',
    'Ranked by the number of products they appear in. These are the admin’s best next aliases.',
    '',
    '| Term | Products |',
    '|---|---:|',
    ...r.topUnmatched.slice(0, 60).map((u) => `| ${u.term} | ${u.products} |`),
    '',
    '## What triggered each rule',
    '',
    'For each flagged rule, the label text that matched it, used to audit false positives.',
    '',
  ];
  for (const ing of [...rules.bundle.ingredients].filter((i) => i.tier !== 'neutral').sort((a, b) => a.name.localeCompare(b.name))) {
    const t = r.triggers[ing.id];
    if (!t?.length) continue;
    lines.push(`- **${ing.name}** (${ing.tier}): ${t.map((x) => `“${x.text}” ×${x.count}`).join(', ')}`);
  }
  return `${lines.join('\n')}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const rules = starterRules();
  const r = runBenchmark(loadProducts(), rules);
  writeFileSync(resolve(ROOT, 'data/benchmark/report.md'), reportMarkdown(r, rules));
  console.log(`coverage ${pct(r.coverage)} (${r.matchedLeaves}/${r.leaves} items, ${r.products} products, ${r.fullyCovered} fully covered)`);
  for (const [k, v] of Object.entries(r.byCountry)) console.log(`  ${k}: ${pct(v.coverage)} over ${v.products}`);
  console.log('top unmatched:', r.topUnmatched.slice(0, 40).map((u) => `${u.term} (${u.products})`).join(', '));
}
